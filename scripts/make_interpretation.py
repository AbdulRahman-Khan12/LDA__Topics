"""Write docs/topic_interpretation.md - the topic interpretation report.

    python scripts/make_interpretation.py

Every number is read from data/artifacts/, so the document cannot drift from
the model outputs. The labels come from data/labels.json, which is the one
human judgement in the pipeline.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from lda_topics.config import ARTIFACT_DIR, CORPUS_FILE, DOCS_DIR  # noqa: E402

topics = list(csv.DictReader((ARTIFACT_DIR / "topics.csv").open(encoding="utf-8")))
matching = list(csv.DictReader((ARTIFACT_DIR / "topic_matching.csv").open(encoding="utf-8")))
metrics = json.loads((ARTIFACT_DIR / "metrics.json").read_text(encoding="utf-8"))
titles = {}
with CORPUS_FILE.open(encoding="utf-8") as fh:
    for line in fh:
        d = json.loads(line)
        titles[d["doc_id"]] = d["title"]

c, s = metrics["corpus"], metrics["settings"]
out = ["# Topic interpretation report", "",
       "Generated by `scripts/make_interpretation.py` from `data/artifacts/`.", "",
       "## Setup", "",
       f"- Corpus: {c['documents']} Reuters-21578 articles, {c['categories']} categories, "
       f"{c['train_docs']} for training and {c['heldout_docs']} held out.",
       f"- Preprocessing: {c['raw_tokens']:,} spaCy tokens -> {c['content_lemmas']:,} content lemmas -> "
       f"{c['dtm_tokens']:,} tokens over a {c['vocabulary']:,}-word vocabulary "
       f"(min_df={s['min_df']}, max_df={s['max_df']}); the document-term matrix is "
       f"{c['sparsity']:.1%} zeros.",
       f"- Model: K={s['K']}, alpha={s['alpha']}, eta={s['eta']}. Variational Bayes for "
       f"{s['vb_max_iter']} iterations; collapsed Gibbs for {s['gibbs_iters']} sweeps, burn-in "
       f"{s['gibbs_burn_in']}, averaging every {s['gibbs_thin']}th sample.", "",
       "## Quality", "",
       "| Model | NPMI | UMass | Perplexity | Diversity | NMI | Purity |", "|---|---|---|---|---|---|---|"]
for name in ("variational", "gibbs"):
    m = metrics["models"][name]
    out.append(f"| {name} | {m['npmi']} | {m['umass']} | {m['perplexity']} | {m['diversity']} | "
               f"{m['nmi']} | {m['purity']} |")
for name in ("variational", "gibbs"):
    out += ["", f"## Topics - {name}", ""]
    for t in [t for t in topics if t["model"] == name]:
        out += [f"### T{t['topic']} - {t['label'] or '(unlabelled)'}", "",
                f"- **Top words (probability):** {t['top_words']}",
                f"- **Most relevant words (lambda=0.6):** {t['relevant_words']}",
                f"- **Prevalence:** {float(t['prevalence']):.1%} of all tokens · NPMI {t['npmi']}",
                f"- **Dominant topic of {t['n_docs_dominant']} documents**, "
                f"{float(t['category_share']):.0%} of them in category `{t['dominant_category']}`",
                "- **Representative documents:** " + "; ".join(
                    f"{titles.get(d, d)}" for d in t["representative_docs"].split()), ""]
out += ["## Variational vs Gibbs", "",
        f"Mean Jensen-Shannon distance between matched topics: {metrics['agreement']['mean_js']}; "
        f"mean overlap of top-10 words: {metrics['agreement']['mean_top10_overlap']}/10.", "",
        "| VB topic | Gibbs topic | JS distance | Top-10 overlap | Shared words |", "|---|---|---|---|---|"]
for m in matching:
    out.append(f"| T{m['vb_topic']} | T{m['gibbs_topic']} | {m['js_distance']} | "
               f"{m['top10_overlap']} | {m['shared_words']} |")
DOCS_DIR.mkdir(exist_ok=True)
(DOCS_DIR / "topic_interpretation.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote docs/topic_interpretation.md")
